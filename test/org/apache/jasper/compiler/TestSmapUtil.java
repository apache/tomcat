package org.apache.jasper.compiler;

import java.io.File;
import java.net.URL;
import java.net.URLClassLoader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;

import org.junit.Assert;
import org.junit.Test;

import org.apache.catalina.startup.TomcatBaseTest;

public class TestSmapUtil extends TomcatBaseTest {

    // The SMAP of a Jasper generated class. The content is valid for
    // loadSmap() and follows the format generated by SmapStratum.
    private static final String SMAP = "SMAP\n" +
            "test.jsp\n" +
            "JSP\n" +
            "*S JSP\n" +
            "*F\n" +
            "+ 0 test.jsp\n" +
            "test.jsp\n" +
            "*L\n" +
            "1,4:120,0\n" +
            "*E\n";

    @Test
    public void testLoadSmapFromDebugExtension() throws Exception {
        // A class file that only contains the SMAP in the (simulated)
        // SourceDebugExtension attribute at the end of the file
        URLClassLoader cl = writeClass("clean", "CAFEBABE junk".getBytes(StandardCharsets.ISO_8859_1));

        SmapStratum smapStratum = SmapUtil.loadSmap("clean", cl);

        Assert.assertNotNull(smapStratum);
        Assert.assertEquals(SMAP, smapStratum.toString());
    }

    @Test
    public void testLoadSmapWithMarkerInConstantPool() throws Exception {
        // Jasper does not read the class file as described by the JLS so a
        // string constant in the constant pool that contains "SMAP\n" (which
        // a page with the word "SMAP" at the end of a line of template text
        // produces) must not be mistaken for the start of the SMAP. The SMAP
        // of the SourceDebugExtension attribute has to be extracted even
        // though an earlier occurrence of the marker is present.
        byte[] junk =
                "CAFEBABE constant pool junk that ends a line of template text with SMAP\nfake content\n"
                        .getBytes(StandardCharsets.ISO_8859_1);

        URLClassLoader cl = writeClass("junk", junk);

        SmapStratum smapStratum = SmapUtil.loadSmap("junk", cl);

        Assert.assertNotNull("SMAP extraction found the marker in the constant pool junk", smapStratum);
        Assert.assertEquals(SMAP, smapStratum.toString());
    }

    /**
     * Writes a file named [name].class to the test temporary directory. The
     * content simulates the end of a compiled JSP class file: the given data
     * followed by the SMAP, since Jasper places the SourceDebugExtension
     * attribute last and loadSmap() does not parse the class file structure.
     *
     * @return a class loader for the directory containing the file
     */
    private URLClassLoader writeClass(String name, byte[] data) throws Exception {
        File file = new File(getTemporaryDirectory(), name + ".class");

        String classData = new String(data, StandardCharsets.ISO_8859_1) + SMAP;
        Files.writeString(file.toPath(), classData, StandardCharsets.ISO_8859_1);

        return new URLClassLoader(new URL[] { file.getParentFile().toURI().toURL() });
    }
}
