package org.apache.jasper.compiler;

import java.io.ByteArrayOutputStream;
import java.io.DataOutputStream;
import java.io.File;
import java.io.IOException;
import java.net.URL;
import java.net.URLClassLoader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collections;
import java.util.List;

import org.junit.After;
import org.junit.Assert;
import org.junit.Test;

import org.apache.catalina.startup.ExpandWar;
import org.apache.catalina.startup.TomcatBaseTest;

public class TestSmapUtil extends TomcatBaseTest {

    // The SMAP of a Jasper generated class. The content is valid for loadSmap() and follows the format generated by
    // SmapStratum.
    private static final String SMAP = smap("test.jsp");

    private final List<File> dirs = new ArrayList<>();
    private final List<URLClassLoader> loaders = new ArrayList<>();


    @After
    public void cleanUp() throws IOException {
        for (URLClassLoader loader : loaders) {
            loader.close();
        }
        loaders.clear();
        for (File dir : dirs) {
            ExpandWar.delete(dir);
        }
        dirs.clear();
    }


    private static String smap(String fileName) {
        return "SMAP\n" + "test_jsp.java\n" + "JSP\n" + "*S JSP\n" + "*F\n" + "+ 0 " + fileName + "\n" + fileName +
                "\n" + "*L\n" + "1,4:120,0\n" + "*E\n";
    }


    @Test
    public void testLoadSmapFromDebugExtension() throws Exception {
        ClassFile classFile = new ClassFile().sde(SMAP);

        SmapStratum smapStratum = SmapUtil.loadSmap("Test", writeClass(classFile));

        Assert.assertNotNull(smapStratum);
        Assert.assertEquals(SMAP, smapStratum.toString());
    }


    @Test
    public void testLoadSmapWithMarkerInConstantPool() throws Exception {
        // A string constant in the constant pool that contains "SMAP\n" (which a page with the word "SMAP" at the end
        // of a line of template text produces) must not be mistaken for the start of the SMAP, wherever it is in the
        // class file.
        ClassFile classFile = new ClassFile().constant("template text that ends a line with SMAP\nfake content\n")
                .sde(SMAP).constant("more text ending with SMAP\nafter the name of the attribute\n");

        SmapStratum smapStratum = SmapUtil.loadSmap("Test", writeClass(classFile));

        Assert.assertNotNull(smapStratum);
        Assert.assertEquals(SMAP, smapStratum.toString());
    }


    @Test
    public void testLoadSmapWithMarkerInSmap() throws Exception {
        // The marker also appears within the SMAP if the name of a source file ends with "SMAP"
        String smapWithMarker = smap("ERRORS.SMAP");
        ClassFile classFile = new ClassFile().sde(smapWithMarker);

        SmapStratum smapStratum = SmapUtil.loadSmap("Test", writeClass(classFile));

        Assert.assertNotNull(smapStratum);
        Assert.assertEquals(smapWithMarker, smapStratum.toString());
    }


    @Test
    public void testLoadSmapWithOtherAttributes() throws Exception {
        // Attributes on the class before the SourceDebugExtension attribute, one of which contains the marker, and
        // members that have attributes
        ClassFile classFile = new ClassFile().wideConstants().member().classAttribute("Other", "SMAP\nnot this\n")
                .sde(SMAP);

        SmapStratum smapStratum = SmapUtil.loadSmap("Test", writeClass(classFile));

        Assert.assertNotNull(smapStratum);
        Assert.assertEquals(SMAP, smapStratum.toString());
    }


    @Test
    public void testLoadSmapWithMultipleDebugExtensionNames() throws Exception {
        // More than one entry in the constant pool with the name of the attribute, one of which is for an attribute
        // that does not contain a SMAP and that comes after the SMAP
        ClassFile classFile = new ClassFile().sdeName().sde(SMAP).sde("not a SMAP\nSMAP\nfake content\n").sdeName();

        SmapStratum smapStratum = SmapUtil.loadSmap("Test", writeClass(classFile));

        Assert.assertNotNull(smapStratum);
        Assert.assertEquals(SMAP, smapStratum.toString());
    }


    @Test
    public void testLoadSmapWithOtherDebugExtensionFirst() throws Exception {
        // An attribute that does not contain a SMAP, before the one that does
        ClassFile classFile = new ClassFile().sde("not a SMAP\nSMAP\nfake content\n").sde(SMAP);

        SmapStratum smapStratum = SmapUtil.loadSmap("Test", writeClass(classFile));

        Assert.assertNotNull(smapStratum);
        Assert.assertEquals(SMAP, smapStratum.toString());
    }


    @Test
    public void testLoadSmapWithOnlyOtherDebugExtension() throws Exception {
        // The only SourceDebugExtension attribute does not contain a SMAP
        ClassFile classFile = new ClassFile().sde("not a SMAP\nSMAP\nfake content\n");

        Assert.assertNull(SmapUtil.loadSmap("Test", writeClass(classFile)));
    }


    @Test
    public void testLoadSmapWithMultipleSmaps() throws Exception {
        // The last SMAP is used since that is where the SourceDebugExtension attribute is added
        ClassFile classFile = new ClassFile().sde(smap("first.jsp")).sde(SMAP);

        SmapStratum smapStratum = SmapUtil.loadSmap("Test", writeClass(classFile));

        Assert.assertNotNull(smapStratum);
        Assert.assertEquals(SMAP, smapStratum.toString());
    }


    @Test
    public void testLoadSmapWithoutDebugExtension() throws Exception {
        // The name of the attribute is present but there is no such attribute. The only occurrence of the marker is in
        // a constant.
        ClassFile classFile = new ClassFile().constant("text ending with SMAP\nfake content\n").sdeName();

        Assert.assertNull(SmapUtil.loadSmap("Test", writeClass(classFile)));
    }


    @Test
    public void testLoadSmapWithoutDebugExtensionName() throws Exception {
        ClassFile classFile = new ClassFile().constant("text ending with SMAP\nfake content\n");

        Assert.assertNull(SmapUtil.loadSmap("Test", writeClass(classFile)));
    }


    @Test
    public void testLoadSmapNotAClassFile() throws Exception {
        File dir = createDir();
        Files.write(new File(dir, "Test.class").toPath(),
                ("CAFEBABE junk\n" + SMAP).getBytes(StandardCharsets.ISO_8859_1));

        Assert.assertNull(SmapUtil.loadSmap("Test", loader(dir)));
    }


    @Test
    public void testLoadSmapTruncatedClassFile() throws Exception {
        byte[] bytes = new ClassFile().sde(SMAP).toBytes();
        File dir = createDir();
        // Truncate in the middle of the SourceDebugExtension attribute
        Files.write(new File(dir, "Test.class").toPath(), Arrays.copyOf(bytes, bytes.length - 10));

        Assert.assertNull(SmapUtil.loadSmap("Test", loader(dir)));
    }


    @Test
    public void testInstallAndLoadSmap() throws Exception {
        // Install the SMAP with the code that Jasper uses and then load it again
        ClassFile classFile = new ClassFile().constant("text ending with SMAP\nfake content\n");
        File dir = createDir();
        File file = new File(dir, "Test.class");
        Files.write(file.toPath(), classFile.toBytes());

        SmapStratum stratum = new SmapStratum();
        stratum.setOutputFileName("test_jsp.java");
        stratum.setClassFileName(file.getAbsolutePath());
        stratum.addFile("ERRORS.SMAP");
        stratum.addLineData(1, "ERRORS.SMAP", 4, 120, 1);
        SmapUtil.installSmap(Collections.singletonMap("Test", stratum));

        SmapStratum loaded = SmapUtil.loadSmap("Test", loader(dir));

        Assert.assertNotNull(loaded);
        Assert.assertEquals(stratum.getSmapString(), loaded.getSmapString());
    }


    private URLClassLoader writeClass(ClassFile classFile) throws Exception {
        File dir = createDir();
        Files.write(new File(dir, "Test.class").toPath(), classFile.toBytes());
        return loader(dir);
    }


    private File createDir() {
        File dir = new File(getTemporaryDirectory(), "smap-util-" + dirs.size() + "-" + System.nanoTime());
        Assert.assertTrue(dir.mkdirs());
        dirs.add(dir);
        return dir;
    }


    private URLClassLoader loader(File dir) throws Exception {
        URLClassLoader loader = new URLClassLoader(new URL[] { dir.toURI().toURL() });
        loaders.add(loader);
        return loader;
    }


    /*
     * Builds a minimal but structurally valid class file. The constant pool contains the entries required by the class
     * plus any that are added. The SourceDebugExtension attribute, if there is one, is the last attribute.
     */
    private static class ClassFile {

        // Constants added before the first attribute or name (constants) and after it (laterConstants)
        private final List<String> constants = new ArrayList<>();
        private final List<String> laterConstants = new ArrayList<>();
        private final List<String[]> attributes = new ArrayList<>();
        private boolean sdeName;
        private boolean wide;
        private boolean member;

        ClassFile constant(String value) {
            if (sdeName || !attributes.isEmpty()) {
                laterConstants.add(value);
            } else {
                constants.add(value);
            }
            return this;
        }

        /*
         * Adds the name of the SourceDebugExtension attribute to the constant pool without adding the attribute.
         */
        ClassFile sdeName() {
            sdeName = true;
            return this;
        }

        /*
         * Adds a SourceDebugExtension attribute. Each attribute has its own entry in the constant pool for its name so
         * adding more than one results in more than one entry with the name of the attribute.
         */
        ClassFile sde(String value) {
            return classAttribute("SourceDebugExtension", value);
        }

        ClassFile wideConstants() {
            wide = true;
            return this;
        }

        ClassFile member() {
            member = true;
            return this;
        }

        ClassFile classAttribute(String name, String value) {
            attributes.add(new String[] { name, value });
            return this;
        }

        byte[] toBytes() throws IOException {
            ByteArrayOutputStream baos = new ByteArrayOutputStream();
            DataOutputStream out = new DataOutputStream(baos);

            // Constant pool: 1 Utf8, 2 Class, 3 Utf8, 4 Class, then the optional entries
            ByteArrayOutputStream pool = new ByteArrayOutputStream();
            DataOutputStream poolOut = new DataOutputStream(pool);
            poolOut.writeByte(1);
            poolOut.writeUTF("Test");
            poolOut.writeByte(7);
            poolOut.writeShort(1);
            poolOut.writeByte(1);
            poolOut.writeUTF("java/lang/Object");
            poolOut.writeByte(7);
            poolOut.writeShort(3);
            int count = 5;

            for (String constant : constants) {
                poolOut.writeByte(1);
                poolOut.writeUTF(constant);
                count++;
            }
            if (sdeName) {
                poolOut.writeByte(1);
                poolOut.writeUTF("SourceDebugExtension");
                count++;
            }
            int[] attributeNameIndexes = new int[attributes.size()];
            for (int i = 0; i < attributes.size(); i++) {
                poolOut.writeByte(1);
                poolOut.writeUTF(attributes.get(i)[0]);
                attributeNameIndexes[i] = count++;
            }
            if (wide) {
                // Long and double take two entries in the constant pool
                poolOut.writeByte(5);
                poolOut.writeLong(1L);
                count += 2;
                poolOut.writeByte(6);
                poolOut.writeDouble(1.0d);
                count += 2;
            }
            for (String constant : laterConstants) {
                poolOut.writeByte(1);
                poolOut.writeUTF(constant);
                count++;
            }
            // Name and descriptor of the member
            int memberNameIndex = 1;

            out.writeInt(0xCAFEBABE);
            out.writeShort(0); // minor
            out.writeShort(65); // major
            out.writeShort(count);
            out.write(pool.toByteArray());
            out.writeShort(0x21); // access
            out.writeShort(2); // this
            out.writeShort(4); // super
            out.writeShort(0); // interfaces
            out.writeShort(0); // fields
            if (member) {
                // One method with one attribute that contains the marker
                out.writeShort(1);
                out.writeShort(0x1); // access
                out.writeShort(memberNameIndex);
                out.writeShort(memberNameIndex);
                out.writeShort(1);
                out.writeShort(memberNameIndex);
                byte[] data = "SMAP\nin a member\n".getBytes(StandardCharsets.ISO_8859_1);
                out.writeInt(data.length);
                out.write(data);
            } else {
                out.writeShort(0);
            }
            out.writeShort(attributes.size());
            for (int i = 0; i < attributes.size(); i++) {
                out.writeShort(attributeNameIndexes[i]);
                byte[] data = attributes.get(i)[1].getBytes(StandardCharsets.ISO_8859_1);
                out.writeInt(data.length);
                out.write(data);
            }
            out.flush();
            return baos.toByteArray();
        }
    }
}
