package org.apache.jasper.compiler;

import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.List;

import org.junit.After;
import org.junit.Assert;
import org.junit.Test;

import org.apache.catalina.startup.ExpandWar;
import org.apache.catalina.startup.Tomcat;
import org.apache.catalina.startup.TomcatBaseTest;
import org.apache.tomcat.util.buf.ByteChunk;

public class TestParserController extends TomcatBaseTest {

    private final List<File> appDirs = new ArrayList<>();

    @After
    public void deleteAppDirs() {
        // Remove the web applications generated by the tests
        for (File appDir : appDirs) {
            ExpandWar.delete(appDir);
        }
        appDirs.clear();
    }


    private File createAppDir(String name) {
        File appDir = new File(getTemporaryDirectory(), name);
        Assert.assertTrue(appDir.mkdirs() || appDir.isDirectory());
        appDirs.add(appDir);
        return appDir;
    }


    @Test
    public void testIncludeInvalidUri() throws Exception {
        getTomcatInstanceTestWebapp(false, true);

        ByteChunk res = new ByteChunk();
        int sc = getUrl("http://localhost:" + getPort() + "/test/jsp/parsing/include-invalid-uri.jsp", res, null);

        Assert.assertEquals(500, sc);

        // The report should include the translation error for the invalid
        // include. The error handling code previously threw a
        // NullPointerException itself which was reported instead.
        String result = res.toString();
        Assert.assertTrue(result, result.contains("The include [a b.jsp] is invalid"));
        Assert.assertFalse(result, result.contains("Cannot invoke"));
    }

    @Test
    public void testJspRootDetection() throws Exception {
        // The pages for these tests are generated rather than stored with the
        // tests so that the output, which is compared exactly, always uses
        // Unix line endings for the template text
        Tomcat tomcat = getTomcatInstance();
        File appDir = createAppDir("root-detection");

        // The root element may use any prefix as long as the prefix is bound
        // to the exact JSP namespace URI
        Files.writeString(new File(appDir, "jsp.jsp").toPath(),
                "<jsp:root xmlns:jsp=\"" + TagConstants.JSP_URI + "\" version=\"2.0\">\n" +
                        "<jsp:body>OK</jsp:body>\n</jsp:root>\n", StandardCharsets.UTF_8);
        Files.writeString(new File(appDir, "other.jsp").toPath(),
                "<mypfx:root xmlns:mypfx=\"" + TagConstants.JSP_URI + "\" version=\"2.0\">\n" +
                        "<mypfx:body>OK</mypfx:body>\n</mypfx:root>\n", StandardCharsets.UTF_8);

        tomcat.addWebapp(null, "/test", appDir.getAbsolutePath());
        tomcat.start();

        // Both pages must be parsed as JSP documents. They are handled as XML
        // syntax so, as the output below shows, only the body content is
        // written; the whitespace text between the elements is removed
        ByteChunk res = new ByteChunk();
        int sc = getUrl("http://localhost:" + getPort() + "/test/jsp.jsp", res, null);
        Assert.assertEquals(200, sc);
        Assert.assertEquals("OK", res.toString());

        res = new ByteChunk();
        sc = getUrl("http://localhost:" + getPort() + "/test/other.jsp", res, null);
        Assert.assertEquals(200, sc);
        Assert.assertEquals("OK", res.toString());
    }

    @Test
    public void testJspRootDetectionOtherPrefixDeclaredFirst() throws Exception {
        // Other namespace declarations on the root element, including ones whose prefix starts with the prefix of the
        // root element, must not hide the declaration of the prefix of the root element
        Tomcat tomcat = getTomcatInstance();
        File appDir = createAppDir("root-detection-prefixes");

        Files.writeString(new File(appDir, "first.jsp").toPath(),
                "<jsp:root xmlns:jspx=\"urn:example:other\" xmlns:jsp=\"" + TagConstants.JSP_URI +
                        "\" version=\"2.0\">\n<jsp:body>OK</jsp:body>\n</jsp:root>\n", StandardCharsets.UTF_8);
        // The prefix of the root is also a suffix of another declared prefix
        Files.writeString(new File(appDir, "suffix.jsp").toPath(),
                "<jsp:root xmlns:myjsp=\"urn:example:other\" xmlns:jsp=\"" + TagConstants.JSP_URI +
                        "\" version=\"2.0\">\n<jsp:body>OK</jsp:body>\n</jsp:root>\n", StandardCharsets.UTF_8);

        tomcat.addWebapp(null, "/test", appDir.getAbsolutePath());
        tomcat.start();

        for (String page : new String[] { "first.jsp", "suffix.jsp" }) {
            ByteChunk res = new ByteChunk();
            int sc = getUrl("http://localhost:" + getPort() + "/test/" + page, res, null);
            Assert.assertEquals(page, 200, sc);
            Assert.assertEquals(page, "OK", res.toString());
        }
    }


    @Test
    public void testRootNamespaceTextInAttributeValue() throws Exception {
        Tomcat tomcat = getTomcatInstance();
        File appDir = createAppDir("root-quoted-namespace");
        List<String> pages = new ArrayList<>();
        for (char quote : new char[] { '"', '\'' }) {
            char innerQuote = quote == '"' ? '\'' : '"';
            // Check the real declaration before and after the attribute value, and an undeclared prefix. None of
            // these pages is a JSP document, even though the attribute value contains a JSP namespace declaration.
            for (int declaration = 0; declaration < 3; declaration++) {
                String namespace = "xmlns:foo=\"urn:example\"";
                String content = "<foo:root xmlns:foobar=\"urn:other\" " +
                        (declaration == 0 ? namespace + " " : "") + "data=" + quote + " xmlns:foo=" +
                        innerQuote + TagConstants.JSP_URI + innerQuote + quote +
                        (declaration == 1 ? " " + namespace : "") + ">\n<p>hello</p>\n</foo:root>\n";
                String page = "quoted-" + pages.size() + ".jsp";
                Files.writeString(new File(appDir, page).toPath(), content, StandardCharsets.UTF_8);
                pages.add(page);
            }
        }

        tomcat.addWebapp(null, "/test", appDir.getAbsolutePath());
        tomcat.start();

        for (String page : pages) {
            ByteChunk res = new ByteChunk();
            int sc = getUrl("http://localhost:" + getPort() + "/test/" + page, res, null);
            Assert.assertEquals(page, 200, sc);
            Assert.assertEquals(page, Files.readString(new File(appDir, page).toPath(), StandardCharsets.UTF_8),
                    res.toString());
        }
    }


    @Test
    public void testJspRootDetectionGreaterThanInAttributeValue() throws Exception {
        // A '>' within a quoted attribute value does not end the root element, so the declaration of the prefix that
        // follows the attribute must still be found
        Tomcat tomcat = getTomcatInstance();
        File appDir = createAppDir("root-detection-gt");

        Files.writeString(new File(appDir, "double.jsp").toPath(),
                "<jsp:root xmlns:x=\"urn:a>b\" xmlns:jsp=\"" + TagConstants.JSP_URI +
                        "\" version=\"2.0\">\n<jsp:body>OK</jsp:body>\n</jsp:root>\n", StandardCharsets.UTF_8);
        Files.writeString(new File(appDir, "single.jsp").toPath(),
                "<jsp:root xmlns:x='urn:a>\"b' xmlns:jsp='" + TagConstants.JSP_URI +
                        "' version='2.0'>\n<jsp:body>OK</jsp:body>\n</jsp:root>\n", StandardCharsets.UTF_8);
        // A '>' in an attribute value of a root element that is not bound to the JSP namespace must not make the
        // page a JSP document
        Files.writeString(new File(appDir, "other.jsp").toPath(),
                "<foo:root data=\"a>xmlns:foo='" + TagConstants.JSP_URI + "'\" xmlns:foo=\"urn:example\">\n" +
                        "<p>hello</p>\n</foo:root>\n", StandardCharsets.UTF_8);

        tomcat.addWebapp(null, "/test", appDir.getAbsolutePath());
        tomcat.start();

        for (String page : new String[] { "double.jsp", "single.jsp" }) {
            ByteChunk res = new ByteChunk();
            int sc = getUrl("http://localhost:" + getPort() + "/test/" + page, res, null);
            Assert.assertEquals(page, 200, sc);
            Assert.assertEquals(page, "OK", res.toString());
        }

        ByteChunk res = new ByteChunk();
        int sc = getUrl("http://localhost:" + getPort() + "/test/other.jsp", res, null);
        Assert.assertEquals(200, sc);
        Assert.assertEquals(Files.readString(new File(appDir, "other.jsp").toPath(), StandardCharsets.UTF_8),
                res.toString());
    }


    @Test
    public void testRootPrefixNamespaceIsNotJspDocument() throws Exception {
        // A namespace that only starts with the JSP namespace URI must not
        // trigger parsing as a JSP document
        Tomcat tomcat = getTomcatInstance();
        File appDir = createAppDir("root-prefix");
        Files.writeString(new File(appDir, "prefix.jsp").toPath(),
                "<foo:root xmlns:foo=\"" + TagConstants.JSP_URI + "PageExtra\">\n" +
                        "<p>hello</p>\n</foo:root>\n", StandardCharsets.UTF_8);

        tomcat.addWebapp(null, "/test", appDir.getAbsolutePath());
        tomcat.start();

        ByteChunk res = new ByteChunk();
        int sc = getUrl("http://localhost:" + getPort() + "/test/prefix.jsp", res, null);

        Assert.assertEquals(200, sc);

        // The page must be handled as standard syntax: the template text,
        // including the line breaks written above, is output unchanged and no
        // XML declaration is added
        String result = res.toString();
        Assert.assertTrue(result, result.contains("PageExtra\">\n<p>hello</p>"));
        Assert.assertFalse(result, result.contains("<?xml"));
    }
}
